// Midnight Blacksmithing — full recipe database, Stormrage-US.
//
// Sourced from Blizzard's Game Data API (profession/recipe list — id,
// name, category, authoritative) cross-referenced with warcraft.wiki.gg
// and Wowhead spell tooltips (materials, skill level, learn method —
// Blizzard's API does not expose these fields at all). Compiled Aug 2026.
//
// Excluded from this list on purpose:
//   - "Appendix I - Terms" / "Appendix II - Stats" categories —
//     in-game glossary tooltips, not actual craftable recipes.
//   - "Recraft Equipment" — not a materials-in/item-out recipe. It's WoW's
//     cross-profession item-upgrade system, unlocked automatically by
//     knowing the item's base recipe. Doesn't fit this data model.
//
// Field notes:
//   - skillLevelRequired / skillProgression: null where genuinely not
//     published anywhere. Not guessed.
//   - skillProgression is [orange, yellow, green, gray] skill-up
//     thresholds where known — Midnight's numeric skill-point system means
//     several endgame (skill 100) recipes only ever publish 2-3 values
//     (e.g. [100,100,100]) rather than a full 4-value curve.
//   - learnMethod.type: 'automatic' (no unlock needed), 'trainer' (gold,
//     from Bemarrin/Arathel Sunforge in Silvermoon City or Chrysalius in
//     the Voidstorm unless noted), 'specialization' (Knowledge points, no
//     trainer/gold), 'recipe_item' (a separate Design/Plans item — vendor
//     currency, drop, or rep-gated purchase), 'drop' (the recipe itself is
//     a rare drop). null where unconfirmed.
//   - sellable: true/false confirmed BoE-vs-BoP where known; null where
//     genuinely unconfirmed (don't assume either way) — this is common for
//     the newest PvP/endgame recipes in this batch since wiki coverage
//     lags brand-new patch content.
//   - materials[].key: matches WOW_ITEM_IDS keys in
//     ../itemIds/midnight-blacksmithing.js for AH sync. A material with
//     qty: null means the source didn't publish an exact quantity.
//
// Research notes worth knowing before trusting a specific number:
//   - Several "Sparks"-keyed materials across endgame weapon/armor recipes
//     are recorded under the literal name "Sparks"/"Spark" as shown on the
//     source page — this is very likely shorthand for a longer, specific
//     reagent name that isn't resolvable to a stable item ID yet (same
//     pattern as Jewelcrafting's unmapped "Spark"/"Competitor's Heraldry").
//   - A few recipes have internally-inconsistent source data (e.g. a
//     skill-up progression value out of monotonic order, or a learn-method
//     skill gate that doesn't match the stated Knowledge-point unlock) —
//     recorded as-fetched rather than "corrected" to a guess. See git
//     history / research batch notes if a specific number looks wrong.
//
// Built alongside Leatherworking following the process documented in
// docs/wow-tracker-playbook.md — same /wow/{expansion}/{profession}
// structure as Jewelcrafting.
