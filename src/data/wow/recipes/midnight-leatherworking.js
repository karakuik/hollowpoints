//     knowing the item's base recipe. Doesn't fit this data model.
//
// Field notes:
//   - skillLevelRequired / skillProgression: null where genuinely not
//     published anywhere. Not guessed. Midnight appears to have moved away
//     from the classic orange/yellow/green/gray skill-up-color mechanic for
//     most Leatherworking recipes — skillProgression is null far more often
//     here than in Jewelcrafting/Blacksmithing; treat any populated array
//     as a genuine source quote, not an assumed-present field.
//   - learnMethod.type: 'automatic' (no unlock needed, e.g. Smuggler's
//     Leather Wristbands — one of two starting recipes), 'trainer' (gold,
//     from Talmar in Silvermoon City or Jan'zel/Zavahi in Zul'Aman unless
//     noted), 'specialization' (Knowledge points, no trainer/gold),
//     'recipe_item' (a separate Pattern/Design item — vendor currency
//     [often "Artisan Leatherworker's Moxie"], drop, or rep-gated
//     purchase), 'drop' (the recipe itself is a rare drop). null where
//     unconfirmed.
//   - sellable: true/false confirmed BoE-vs-BoP where known; null where
//     genuinely unconfirmed — very common in this file since most
//     Competitor's-tier and epic drop-pattern gear had no live wiki page to
//     confirm binding on at research time (brand-new patch content).
//   - materials[].key: matches WOW_ITEM_IDS keys in
//     ../itemIds/midnight-leatherworking.js for AH sync. A material with
//     qty: null means the source didn't publish an exact quantity (seen a
//     few times on "Spark"/"Sin'dorei Armor Banding" reagent lines).
//
// Research notes worth knowing before trusting a specific number:
//   - 'Fused Vitality' quantities are ambiguous across ~8 Profession
//     Equipment recipes — sources showed two different item IDs both
//     labeled "Fused Vitality", one needing qty 20 and one qty 40 (likely a
//     hidden reagent-quality tier, same pattern as Jewelcrafting's
//     duplicate-ID materials). qty 20 was recorded as the primary value;
//     verify in-game before trusting it exactly.
//   - The 16-piece Competitor's Leather/Mail Armor PvP set is gated behind
//     a vendor (Mirvedon, Silvermoon City, ~7,500 Honor per pattern) but
//     individual skill levels/progression/binding could only be confirmed
//     for 2 of the 16 (both mail pieces, skill 50) — the wiki pages for the
//     rest are red-links as of this research pass (very new patch content).
//   - 'Spark' (Leather Armor set) and 'Spark of the Void' (Mail Armor set)
//     are recorded as separate, distinctly-named reagents exactly as shown
//     on their respective sources — unclear if these are the same item
//     under different display names or genuinely different reagents;
//     neither resolves to a stable item ID yet (see itemIds file).
