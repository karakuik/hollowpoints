//     cross-profession item-upgrade system (modify an already-crafted
//     item's optional reagents/embellishments), unlocked automatically by
//     knowing the item's base recipe. Doesn't fit this data model.
//
// Field notes:
//   - skillLevelRequired / skillProgression: null where genuinely not
//     published anywhere (all 18 Lustrous Lapis / Austere Amethysts
//     recipes have no warcraft.wiki.gg page yet — very new patch content,
//     Feb 2026). Not guessed.
//   - skillProgression is [orange, yellow, green, gray] skill-up
//     thresholds where known — the recipe stops granting skill at the
//     last number.
//   - learnMethod.type: 'automatic' (no unlock needed), 'trainer' (gold,
//     from Aleinia/Amin/Kalinda in Silvermoon City unless noted),
//     'specialization' (Knowledge points, no trainer/gold), 'recipe_item'
//     (a separate Design/Pattern item — vendor currency, drop, or rep-gated
//     purchase), 'drop' (the recipe itself is a rare drop). null where
//     unconfirmed.
//   - sellable: true/false confirmed BoE-vs-BoP where known; null where
//     genuinely unconfirmed (don't assume either way).
//   - materials[].key: matches WOW_ITEM_IDS keys in wowItemIds.js for AH
//     sync. Some materials (Spark, Competitor's Heraldry) have no stable
//     mapped ID — see wowItemIds.js for why.

